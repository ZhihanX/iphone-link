  function detectLang(locale) {
    const l = String(locale || (typeof navigator !== 'undefined' ? navigator.language : '') || '').toLowerCase()
    return l.startsWith('zh') ? 'zh' : 'en'
  }

  function t(lang, key, vars) {
    const text = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key
    return text.replace(/\{(\w+)\}/g, (all, name) => (vars && vars[name] !== undefined ? String(vars[name]) : all))
  }

